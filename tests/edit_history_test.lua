-- Player 0.16: 32-step bounded edit history, rotation/scale and recovery snapshots.
package.path="./player-lua/?.lua;./player-lua/?/init.lua;"..package.path
local Package=require("src.package_v9")
local Ex=require("src.game_example_v9")
local Edit=require("src.keyframe_editor")
local History=require("src.edit_history")
local Tween=require("src.sprite_tween")
local game=assert(Package.decode(Ex.bytes()))
local initial=assert(Package.encode(game))
local resources=game.resources
local sourceScene=game.document
local history=History.new(game)
assert(not history:isDirty())
assert(not history:undo())
local before=history:begin(1,2)
assert(Edit.rotate(game,1,2,5))
assert(history:record(before))
assert(game.tweens[1].keys[2].angle==95 and history:isDirty())
local a,b=history:undo(1,2)
assert(a==1 and b==2)
assert(game.tweens[1].keys[2].angle==90)
assert(not history:isDirty())
a,b=history:redo(1,2)
assert(a==1 and b==2 and game.tweens[1].keys[2].angle==95)
assert(history:isDirty())
-- History must not copy binary resources or swap the document.
assert(game.resources==resources and game.document==sourceScene)
assert(game.resources[1].data==resources[1].data)
assert(not Edit.rotate(game,1,2,999))
assert(not Edit.rotate(game,1,2,0/0))
assert(game.tweens[1].keys[2].angle==95)

before=history:begin(1,2)
assert(Edit.scale(game,1,2,"X",10))
assert(Edit.scale(game,1,2,"Y",-10))
assert(history:record(before))
assert(game.tweens[1].keys[2].scaleX==160)
assert(game.tweens[1].keys[2].scaleY==75)
assert(Package.decode(assert(Package.encode(game))))
assert(Tween.new(game):sample(1,23).scaleX==160)
local savepoint=assert(Package.encode(game))
history:markSaved()
assert(not history:isDirty())
before=history:begin(1,2)
assert(not history:record(before),"no-op must not record history")
assert(not history:isDirty())
-- Redo must disappear after a new divergent edit.
history:undo(1,2)
assert(history:isDirty())
before=history:begin(1,2)
assert(Edit.shiftPosition(game,1,2,3,0))
assert(history:record(before))
assert(not history:redo(1,2),"redo invalid after divergence")
assert(game.tweens[1].keys[2].x==33)
-- Pure keyframe CRUD and curve changes participate in the same history.
before=history:begin(1,3)
local at=assert(Edit.insert(game,1,34))
assert(history:record(before))
assert(#game.tweens[1].keys==6)
history:undo(1,at)
assert(#game.tweens[1].keys==5)
history:redo(1,3)
assert(#game.tweens[1].keys==6)
assert(Package.decode(assert(Package.encode(game))))
-- Test history limit: only the most recent 32 changes are retained.
local capGame=assert(Package.decode(Ex.bytes()))
local capped=History.new(capGame)
for _=1,45 do
  local snap=capped:begin(1,2)
  assert(Edit.rotate(capGame,1,2,-1))
  assert(capped:record(snap))
end
assert(#capped.past==32)
local undo=0
while capped:undo(1,2) do undo=undo+1 end
assert(undo==32 and capGame.tweens[1].keys[2].angle==77,
  "limited history should preserve only 32 latest states")
assert(Package.decode(assert(Package.encode(capGame))))
-- Resetting for another imported game must not retain any old changes.
capped:reset(assert(Package.decode(Ex.bytes())))
assert(not capped:isDirty() and not capped:undo() and not capped:redo())
assert(not Edit.scale(game,1,2,"Z",10))
assert(not Edit.scale(game,1,2,"X",1000))
assert(not Edit.scale(game,1,2,"Y",-1000))
assert(not Edit.scale(game,1,2,"X",1/0))
assert(Edit.scale(game,1,2,"X",0))
assert(Package.decode(savepoint))
assert(Package.decode(initial))
print("OK: Player 0.16 safe rotation/scale, undo/redo, dirty state, history cap")
