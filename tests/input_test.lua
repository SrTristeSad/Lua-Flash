package.path="./player-lua/?.lua;./player-lua/?/init.lua;"..package.path
local Model=require("src.model")
local Input=require("src.input")
local Demo=require("src.demo")
local Interpolation=require("src.interpolation")
local Game=require("src.target_game")
local d=Demo.create()
local sampler=Interpolation.new(d)
local router=Input.new()
local vp={x=0,y=0,w=1000,h=500}
assert(Input.stagePoint(5,250,d,vp)==nil,"letterbox must not accept clicks")
local sx,sy=Input.stagePoint(500,250,d,vp)
assert(math.abs(sx-400)<.00001 and math.abs(sy-225)<.00001,"stage scale")
assert(Input.stagePoint(500,-10,d,vp)==nil)
assert(Input.stagePoint(0/0,100,d,vp)==nil)
local px=55.5555555556+127*(500/450)
local py=277*(500/450)
local shape=Input.hitTest(d,1,127,277,sampler)
assert(shape and shape.layer==2 and shape.kind=="ellipse")
local e=router:pointer("down","mouse",1,px,py,d,1,vp,sampler)
assert(e.inside and e.hit and e.hit.layer==2)
e=router:pointer("up","mouse",1,px,py,d,1,vp,sampler)
assert(e.clicked and e.hit.layer==2)
e=router:pointer("up","mouse",1,px,py,d,1,vp,sampler)
assert(not e.clicked)
local key=router:key("down","a")
assert(key.type=="keydown" and router.keys.a)
router:key("up","a")
assert(router.keys.a==nil)
router:pointer("down","mouse",1,px,py,d,1,vp,sampler)
e=router:pointer("up","mouse",1,500,250,d,1,vp,sampler)
assert(not e.clicked)
router:pointer("down","touch",123,px,py,d,1,vp,sampler)
e=router:pointer("up","touch",123,0,0,d,1,vp,sampler)
assert(not e.clicked)
router:pointer("down","touch",123,px,py,d,1,vp,sampler)
router:pointer("cancel","touch",123,px,py,d,1,vp,sampler)
e=router:pointer("up","touch",123,px,py,d,1,vp,sampler)
assert(not e.clicked)
router:pointer("down","mouse",1,px,py,d,1,vp,sampler)
router:reset()
e=router:pointer("up","mouse",1,px,py,d,1,vp,sampler)
assert(not e.clicked)
assert(Input.hitTest(d,1,80,230,sampler).layer==1)
local custom=Model.new(100,100,24)
local line=Model.makeShape("line",{1,0,0},1,5,5)
line.points={5,5,95,95}
custom.layers[1].keys[1]={line}
assert(Input.hitTest(custom,1,50,50).kind=="line")
assert(Input.hitTest(custom,1,15,70)==nil)
local rect=Model.makeShape("rect",{1,1,1},1,0,0)
rect.points={0,0,100,100}
local upper=Model.addLayer(custom)
upper.keys[1]={rect}
assert(Input.hitTest(custom,1,50,50).layer==2)
upper.visible=false
assert(Input.hitTest(custom,1,50,50).layer==1)
local g=Game.new()
assert(g.score==0 and g.remaining==30 and g.active)
assert(g:attempt(shape) and g.score==1)
assert(not g:attempt({layer=1}) and g.misses==1)
g:setReticle(100,120)
g:moveReticle(900,-500,d)
assert(g.reticleX==d.width and g.reticleY==0)
g:update(1/30,true)
assert(g.remaining<30)
local remaining=g.remaining
g:update(1,false)
assert(g.remaining==remaining)
for i=1,200 do g:update(.25,true) end
assert(g.remaining==0 and not g.active)
assert(not g:attempt(shape))
assert(Game.new().score==0)
print("OK: 0.3 pointer, mouse/touch, keyboard and target game")
