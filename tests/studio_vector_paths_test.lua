-- Studio vector authoring: cubic interpolation, editing, fill/stroke and LFVECTOR 1.
package.path="./studio-lua/?.lua;./studio-lua/?/init.lua;"..package.path
local V=require("src.vector_paths")
local v=V.new()
local p=assert(V.addPath(v,1,1,20,30,{.1,.2,.3},3,{.5,.6,.7}))
assert(V.addNode(p,60,30)==2)
assert(V.addNode(p,60,60)==3)
assert(V.handle(p,1,38,12,"out"))
assert(V.handle(p,2,42,12,"in"))
local sampled=V.sample(p,10)
assert(#sampled==42)
assert(sampled[1]==20 and sampled[2]==30)
assert(math.abs(sampled[21]-60)<.00001 and math.abs(sampled[22]-30)<.00001)
assert(V.close(p))
assert(#V.sample(p,10)==62)
local px,py=V.bounds(p)
assert(px<=20 and py<30,"Bezier bounds should include control curvature")
assert(V.hit(p,20,30,4))
assert(V.pick({p},20,30,4)==p)
local picked,node=V.pickNode({p},60,60,5)
assert(picked==p and node==3)
assert(V.moveNode(p,1,25,35))
assert(p.nodes[1].ox==43 and p.nodes[1].oy==17,"move anchor with its control point")
assert(V.move(p,5,5))
assert(p.nodes[1].x==30 and p.nodes[1].y==40)
assert(not V.addNode(p,1,1),"closed path must not accept nodes")
local bytes=V.encode(v)
local round=assert(V.decode(bytes))
assert(V.encode(round)==bytes)
assert(round.nextId==2)
assert(round.tracks[1][1][1].nodes[1].ox==48)
local original=V.encode(round)
local frame=V.ensureKey(round,1,7)
assert(#frame==1)
assert(V.moveNode(frame[1],1,70,70))
assert(round.tracks[1][1][1].nodes[1].x==30,"new exposure must deep copy")
V.ensureKey(round,1,9,true)
assert(#V.at(round,1,10)==0)
assert(V.removeKey(round,1,9))
assert(#V.at(round,1,10)==1)
assert(original==bytes)
assert(not V.decode("LFVECTOR 9\nEND\n"))
assert(not V.decode("LFVECTOR 1\nK\t1\t1\nP\t1\t0\t2\t0,0,0,1\t-\nN\tNaN\t1\t1\t1\t1\t1\nEP\nEK\nEND\n"))
assert(not V.decode("LFVECTOR 1\nK\t1\t1\nP\t1\t1\t2\t0,0,0,1\t-\nN\t1\t1\t1\t1\t1\t1\nEP\nEK\nEND\n"))
assert(not V.decode("LFVECTOR 1\nK\t1\t1\nK\t1\t1\nEND\n"))
print("OK: cubic paths, controls, fill/stroke persistence, key exposure and hostile input")
